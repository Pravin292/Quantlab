"""H1 calibration, STAGE 4, part D: SECOND INDEPENDENT IMPLEMENTATION CHECK (docs/22 section 6; D4 approved).   ALL SIMULATED.
10 cells (stage4_prereg/reference_selection.csv, drawn before any result) x 10 datasets = 100 datasets, generated by the Stage 3 fast generator with SeedSequence(20261208, spawn_key=(val_row, i)).
For each: statistic T from the vectorised code (h1_calibration.max_abs_t) and from the independent exact-arithmetic implementation (h1_stage4_reference); required: relative difference <= 1e-9 and
IDENTICAL C3 decisions (T above the frozen value for the cell's sample size). Also: the five frozen C3 values (59, 90, 125, 180, 250 days) re-derived from the saved training statistics by the
independent quantile routine; required relative difference <= 1e-12.      Output: outputs/milestone4/h1_calibration/stage4/reference/
"""
import argparse
import platform
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import stage4_common as c4                                                 # noqa: E402
import stage3_common as c3c                                                # noqa: E402
from quantlab.research import direct_sim as ds, h1_calibration as hc, h1_stage3 as s3, h1_stage4_reference as ref   # noqa: E402

OUT = c4.S4 / "reference"
TOL_T, TOL_Q = 1e-9, 1e-12
_T2, _T3 = None, None


def _init(t2, t3):
    """Worker start-up: the frozen C3 tables."""
    global _T2, _T3
    _T2, _T3 = t2, t3


def work(job):
    """One dataset: both implementations and the C3 decisions."""
    row, i = job
    cells = c3c.load_validation_cells(); c = {k: cells.loc[row, k] for k in cells.columns}
    setup = c3c.cell_setup(c)
    rng = np.random.default_rng(np.random.SeedSequence(c4.MASTER["reference"], spawn_key=(row, i)))
    r2 = c4.sc.generate(setup, rng)
    t_vec = float(hc.max_abs_t(ds.period_matrix(r2, setup["idx"])))
    t0 = time.perf_counter()
    t_ref = ref.statistic_T(ref.market_matrix(r2.tolist(), c["market"]))
    crit = s3.c3_value(int(c["n_days"]), _T2, _T3)
    return {"val_row": row, "dataset": i, "market": c["market"], "n_days": int(c["n_days"]), "T_vectorised": t_vec, "T_reference": t_ref, "rel_diff": abs(t_ref - t_vec) / abs(t_vec),
            "c3_crit": crit, "reject_vectorised": t_vec > crit, "reject_reference": t_ref > crit, "near_boundary_1e-6": abs(t_vec - crit) / crit < 1e-6, "reference_seconds": time.perf_counter() - t0}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--out", default=None)
    ap.add_argument("--per-cell", type=int, default=10)
    a = ap.parse_args()
    out = Path(a.out) if a.out else OUT
    if a.smoke and (a.out is None or Path(a.out).resolve() == OUT.resolve()):
        sys.exit("--smoke needs --out pointing to a scratch folder")
    checks = c4.verify_all(stage4_inputs=not a.smoke)
    if out.exists() and any(out.iterdir()):
        sys.exit(f"{out} already has files.")
    out.mkdir(parents=True, exist_ok=True)
    sel = pd.read_csv(c4.PREREG / "reference_selection.csv")
    assert len(sel) == 10 and sel.val_row.tolist() == [14, 34, 50, 60, 77, 3, 9, 11, 43, 45], "reference selection differs from the preregistered draw"
    t2 = pd.read_csv(c3c.STAGE2_C3_TABLE).set_index("n_days").c3_crit.to_dict(); t3 = pd.read_csv(c3c.C3I_TABLE).set_index("n_days").c3_crit.to_dict()
    n = a.per_cell if a.smoke else 10
    t0 = time.perf_counter()
    with ProcessPoolExecutor(initializer=_init, initargs=(t2, t3)) as pool:
        D = pd.DataFrame(list(pool.map(work, [(int(r), i) for r in sel.val_row for i in range(n)])))
    D.to_csv(out / "reference_datasets.csv", index=False)
    # re-derivation of the five frozen C3 values from the saved training statistics with the independent quantile routine
    cr2 = pd.read_csv(c4.B / "stage2" / "c3_training" / "c3_training_cell_results.csv", keep_default_na=False)
    cr3 = pd.read_csv(c4.B / "stage3" / "c3_intermediate" / "c3_intermediate_cell_results.csv")
    der = []
    for nd, g in cr2.groupby("n_days"):
        lists = [pd.read_parquet(c4.B / "stage2" / "c3_training" / f"cell_{int(r):02d}.parquet").query("valid")["T"].tolist() for r in g.dev_row]
        v = ref.c3_value(lists); der.append({"n_days": int(nd), "source": "Stage 2 training", "cells": len(lists), "frozen": float(t2[int(nd)]), "rederived": v})
    for nd, g in cr3.groupby("n_days"):
        lists = [pd.read_parquet(c4.B / "stage3" / "c3_intermediate" / f"cell_{int(r):02d}.parquet").query("valid")["T"].tolist() for r in g.row]
        v = ref.c3_value(lists); der.append({"n_days": int(nd), "source": "Stage 3 intermediate training", "cells": len(lists), "frozen": float(t3[int(nd)]), "rederived": v})
    Q = pd.DataFrame(der); Q["rel_diff"] = (Q.rederived - Q.frozen).abs() / Q.frozen
    Q.to_csv(out / "c3_value_rederivation.csv", index=False)
    crit = [("T relative difference <= 1e-9 in all datasets", bool((D.rel_diff <= TOL_T).all()), float(D.rel_diff.max())),
            ("identical C3 decisions in all datasets", bool((D.reject_vectorised == D.reject_reference).all()), int((D.reject_vectorised != D.reject_reference).sum())),
            ("five frozen C3 values re-derived to 1e-12", bool((Q.rel_diff <= TOL_Q).all() and len(Q) == 5), float(Q.rel_diff.max())),
            ("datasets compared", len(D) == 10 * n, len(D))]
    pd.DataFrame([{"criterion": c, "met": m, "value": v} for c, m, v in crit]).to_csv(out / "reference_outcome.csv", index=False)
    pd.Series({"master_seed": c4.MASTER["reference"], "seed_rule": "SeedSequence(20261208, spawn_key=(val_row, i))", "datasets": len(D), "smoke": a.smoke, "wall_seconds": round(time.perf_counter() - t0, 1),
               "python": platform.python_version(), "manifests_verified": str({k: v for k, v in checks.items() if k != "free_gib"}), "note": "ALL DATA SIMULATED"}).to_csv(out / "run_metadata.csv", header=["value"])
    print(D[["val_row", "n_days", "T_vectorised", "T_reference", "rel_diff", "reject_vectorised", "reject_reference"]].describe().round(12).to_string()); print(Q.to_string(index=False))
    print(pd.DataFrame([{"criterion": c, "met": m, "value": v} for c, m, v in crit]).to_string(index=False)); print("COMPLETE", flush=True)


if __name__ == "__main__":
    main()
